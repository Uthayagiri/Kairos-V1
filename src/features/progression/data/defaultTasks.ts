/**
 * Returns all active system default tasks unlocked for the user's level,
 * with any user-configured custom default task timings and schedule presets applied.
 */
export function getUnlockedDefaultTasks(userLevel: number): DefaultTask[] {
  const boundedLevel = Math.max(1, Math.min(100, userLevel));
  const tasks = SYSTEM_DEFAULT_TASKS.filter((task) => task.unlockLevel <= boundedLevel);
  return applyTaskTimingOverrides(tasks);
}
